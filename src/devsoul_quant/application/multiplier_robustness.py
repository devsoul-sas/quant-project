"""Preregistered robustness gate for synthetic Multiplier validation.

The frozen protocol uses development seeds 21--60. Reserved seeds 61--80 are
metadata only and are never generated by this module.
"""

from dataclasses import dataclass
from decimal import Decimal
from enum import StrEnum

from devsoul_quant.application.multiplier_validation import (
    MultiplierMonteCarloReport,
    MultiplierValidationPolicy,
    run_multiplier_monte_carlo,
)
from devsoul_quant.domain.decision import ReversionPolicy
from devsoul_quant.domain.multiplier_outcomes import DirectionalBarrierPolicy
from devsoul_quant.domain.range_regime import RangePolicy, ReferenceMode
from devsoul_quant.domain.robustness_statistics import (
    PairedBootstrapSummary,
    paired_bootstrap_summary,
)
from devsoul_quant.domain.session_risk import SessionRiskPolicy
from devsoul_quant.domain.synthetic_processes import SyntheticProcess, SyntheticScenario
from devsoul_quant.domain.validation import TemporalSplitSpec

_MULTIPLIER_PROCESSES = (
    SyntheticProcess.ORNSTEIN_UHLENBECK,
    SyntheticProcess.RANDOM_WALK,
    SyntheticProcess.GBM,
    SyntheticProcess.VOLATILITY_REGIME,
)


class InvalidMultiplierRobustness(ValueError):
    """Raised when a robustness report cannot preserve preregistered invariants."""


class MultiplierRobustnessDecision(StrEnum):
    """Scientific decision emitted without opening the reserved holdout."""

    ROBUSTNESS_GATE_PASSED = "ROBUSTNESS_GATE_PASSED"
    INSUFFICIENT_SYNTHETIC_STABILITY = "INSUFFICIENT_SYNTHETIC_STABILITY"
    NO_EDGE = "NO_EDGE"


@dataclass(frozen=True, slots=True)
class SensitivitySpec:
    """One named, non-selectable barrier sensitivity cell."""

    name: str
    barrier: DirectionalBarrierPolicy


@dataclass(frozen=True, slots=True)
class FrozenMultiplierRobustnessProtocol:
    """Complete protocol frozen before generating development seeds."""

    development_seeds: tuple[int, ...]
    reserved_holdout_seeds: tuple[int, ...]
    split_spec: TemporalSplitSpec
    validation_policy: MultiplierValidationPolicy
    range_policy: RangePolicy
    reversion_policy: ReversionPolicy
    primary_barrier: DirectionalBarrierPolicy
    sensitivity: tuple[SensitivitySpec, ...]
    risk_policy: SessionRiskPolicy
    scenario_count: int
    volatility: Decimal
    reversion_speed: Decimal
    regimes: tuple[tuple[int, int], ...]
    bootstrap_confidence: Decimal
    bootstrap_resamples: int
    bootstrap_seed: int


@dataclass(frozen=True, slots=True)
class ProcessRobustnessSummary:
    """Paired primary-configuration diagnostics for one synthetic process."""

    process: SyntheticProcess
    paired_brier: PairedBootstrapSummary
    run_count: int
    scored_run_count: int
    strategy_target_rate: Decimal | None
    random_target_rate: Decimal | None
    holdouts_opened: int
    profitability_claim: bool


@dataclass(frozen=True, slots=True)
class SensitivityRobustnessSummary:
    """OU diagnostics for one frozen sensitivity cell."""

    name: str
    paired_brier: PairedBootstrapSummary
    holdouts_opened: int


@dataclass(frozen=True, slots=True)
class RobustnessGateCheck:
    """One auditable preregistered gate condition."""

    name: str
    passed: bool
    observed: str


@dataclass(frozen=True, slots=True)
class MultiplierRobustnessReport:
    """Final development decision; the reserved holdout always remains sealed."""

    decision: MultiplierRobustnessDecision
    passed: bool
    checks: tuple[RobustnessGateCheck, ...]
    primary: tuple[ProcessRobustnessSummary, ...]
    sensitivity: tuple[SensitivityRobustnessSummary, ...]
    holdout_opened: bool = False
    profitability_claim: bool = False
    economic_metrics_available: bool = False


def frozen_multiplier_robustness_protocol() -> FrozenMultiplierRobustnessProtocol:
    """Return the immutable protocol preregistered for seeds 21--60."""
    primary = DirectionalBarrierPolicy(Decimal("0.00005"), Decimal("0.00005"), 5)
    return FrozenMultiplierRobustnessProtocol(
        development_seeds=tuple(range(21, 61)),
        reserved_holdout_seeds=tuple(range(61, 81)),
        split_spec=TemporalSplitSpec(20, 20, 5, 100, 3, 50),
        validation_policy=MultiplierValidationPolicy(20, 5, 5),
        range_policy=RangePolicy(19, ReferenceMode.DISPLACEMENT),
        reversion_policy=ReversionPolicy(Decimal(1), Decimal(0), Decimal(0)),
        primary_barrier=primary,
        sensitivity=(
            SensitivitySpec(
                "barrier-0.000025-horizon-5",
                DirectionalBarrierPolicy(Decimal("0.000025"), Decimal("0.000025"), 5),
            ),
            SensitivitySpec(
                "barrier-0.00005-horizon-3",
                DirectionalBarrierPolicy(Decimal("0.00005"), Decimal("0.00005"), 3),
            ),
            SensitivitySpec("barrier-0.00005-horizon-5-primary", primary),
            SensitivitySpec(
                "barrier-0.00005-horizon-10",
                DirectionalBarrierPolicy(Decimal("0.00005"), Decimal("0.00005"), 10),
            ),
            SensitivitySpec(
                "barrier-0.0001-horizon-5",
                DirectionalBarrierPolicy(Decimal("0.0001"), Decimal("0.0001"), 5),
            ),
        ),
        risk_policy=SessionRiskPolicy(Decimal(10), 5, 2),
        scenario_count=600,
        volatility=Decimal("0.01"),
        reversion_speed=Decimal("0.15"),
        regimes=((10, 300), (100, 300)),
        bootstrap_confidence=Decimal("0.95"),
        bootstrap_resamples=5_000,
        bootstrap_seed=20_261_123,
    )


def _paired_differences(report: MultiplierMonteCarloReport) -> tuple[Decimal, ...]:
    differences: list[Decimal] = []
    for run in report.runs:
        strategy_score = run.strategy.probability_score
        random_score = run.random_baseline.probability_score
        if strategy_score is not None and random_score is not None:
            differences.append(strategy_score.brier_score - random_score.brier_score)
    if not differences:
        raise InvalidMultiplierRobustness("at least one paired scored run is required")
    return tuple(differences)


def _aggregate_target_rate(report: MultiplierMonteCarloReport, *, strategy: bool) -> Decimal | None:
    methods = tuple(run.strategy if strategy else run.random_baseline for run in report.runs)
    entries = sum(method.entries for method in methods)
    if entries == 0:
        return None
    return Decimal(sum(method.targets for method in methods)) / Decimal(entries)


def summarize_process_robustness(
    *,
    process: SyntheticProcess,
    report: MultiplierMonteCarloReport,
    confidence: Decimal,
    resamples: int,
    seed: int,
) -> ProcessRobustnessSummary:
    """Build paired process diagnostics from one Monte Carlo report."""
    return ProcessRobustnessSummary(
        process=process,
        paired_brier=paired_bootstrap_summary(
            _paired_differences(report),
            confidence=confidence,
            resamples=resamples,
            seed=seed,
        ),
        run_count=report.run_count,
        scored_run_count=report.scored_run_count,
        strategy_target_rate=_aggregate_target_rate(report, strategy=True),
        random_target_rate=_aggregate_target_rate(report, strategy=False),
        holdouts_opened=report.holdouts_opened,
        profitability_claim=report.profitability_claim,
    )


def _check(name: str, passed: bool, observed: object) -> RobustnessGateCheck:
    return RobustnessGateCheck(name=name, passed=passed, observed=str(observed))


def evaluate_multiplier_robustness(
    *,
    primary: tuple[ProcessRobustnessSummary, ...],
    sensitivity: tuple[SensitivityRobustnessSummary, ...],
) -> MultiplierRobustnessReport:
    """Apply every preregistered gate without opening the reserved holdout."""
    by_process = {item.process: item for item in primary}
    required = set(_MULTIPLIER_PROCESSES)
    if set(by_process) != required or len(primary) != len(required):
        raise InvalidMultiplierRobustness(
            "primary must contain each synthetic process exactly once"
        )
    ou = by_process[SyntheticProcess.ORNSTEIN_UHLENBECK]
    random_walk = by_process[SyntheticProcess.RANDOM_WALK]

    integrity_runs = all(item.run_count == 40 for item in primary)
    integrity_scored = ou.scored_run_count == 40 and random_walk.scored_run_count == 40
    no_holdouts = all(item.holdouts_opened == 0 for item in primary) and all(
        item.holdouts_opened == 0 for item in sensitivity
    )
    no_profit_claims = all(not item.profitability_claim for item in primary)

    ou_mean = ou.paired_brier.mean_difference < 0
    ou_interval = ou.paired_brier.upper_bound < 0
    ou_wins = ou.paired_brier.negative_count >= 28
    ou_target = (
        ou.strategy_target_rate is not None
        and ou.random_target_rate is not None
        and ou.strategy_target_rate > ou.random_target_rate
    )
    random_walk_control = (
        random_walk.paired_brier.lower_bound <= 0 <= random_walk.paired_brier.upper_bound
        or random_walk.paired_brier.mean_difference >= 0
    )
    nonpositive_processes = sum(item.paired_brier.mean_difference <= 0 for item in primary)
    no_consistent_degradation = all(item.paired_brier.lower_bound <= 0 for item in primary)
    sensitivity_negative = sum(item.paired_brier.mean_difference < 0 for item in sensitivity)
    sensitivity_stable = sum(item.paired_brier.negative_count >= 24 for item in sensitivity)

    checks = (
        _check("integrity.run_count", integrity_runs, tuple(item.run_count for item in primary)),
        _check(
            "integrity.scored_controls",
            integrity_scored,
            (ou.scored_run_count, random_walk.scored_run_count),
        ),
        _check("integrity.holdouts_closed", no_holdouts, no_holdouts),
        _check("integrity.no_profit_claims", no_profit_claims, no_profit_claims),
        _check("ou.mean_delta_negative", ou_mean, ou.paired_brier.mean_difference),
        _check("ou.interval_upper_negative", ou_interval, ou.paired_brier.upper_bound),
        _check("ou.wins_at_least_28", ou_wins, ou.paired_brier.negative_count),
        _check(
            "ou.target_rate_above_random",
            ou_target,
            (ou.strategy_target_rate, ou.random_target_rate),
        ),
        _check("random_walk.no_false_positive", random_walk_control, random_walk.paired_brier),
        _check(
            "stress.nonpositive_processes_at_least_3",
            nonpositive_processes >= 3,
            nonpositive_processes,
        ),
        _check(
            "stress.no_consistent_degradation", no_consistent_degradation, no_consistent_degradation
        ),
        _check("sensitivity.five_cells", len(sensitivity) == 5, len(sensitivity)),
        _check("sensitivity.negative_at_least_4", sensitivity_negative >= 4, sensitivity_negative),
        _check("sensitivity.stable_at_least_3", sensitivity_stable >= 3, sensitivity_stable),
    )
    passed = all(item.passed for item in checks)
    ou_confirmed = ou_mean and ou_interval and ou_wins and ou_target
    decision = (
        MultiplierRobustnessDecision.ROBUSTNESS_GATE_PASSED
        if passed
        else (
            MultiplierRobustnessDecision.INSUFFICIENT_SYNTHETIC_STABILITY
            if ou_confirmed
            else MultiplierRobustnessDecision.NO_EDGE
        )
    )
    return MultiplierRobustnessReport(
        decision=decision,
        passed=passed,
        checks=checks,
        primary=primary,
        sensitivity=sensitivity,
    )


def _scenario(
    process: SyntheticProcess, protocol: FrozenMultiplierRobustnessProtocol
) -> SyntheticScenario:
    return SyntheticScenario(
        process=process,
        seed=0,
        count=protocol.scenario_count,
        volatility=protocol.volatility,
        reversion_speed=protocol.reversion_speed,
        regimes=protocol.regimes,
    )


def _run_cell(
    *,
    process: SyntheticProcess,
    barrier: DirectionalBarrierPolicy,
    protocol: FrozenMultiplierRobustnessProtocol,
) -> MultiplierMonteCarloReport:
    return run_multiplier_monte_carlo(
        scenario=_scenario(process, protocol),
        seeds=protocol.development_seeds,
        split_spec=protocol.split_spec,
        policy=protocol.validation_policy,
        range_policy=protocol.range_policy,
        reversion_policy=protocol.reversion_policy,
        barrier_policy=barrier,
        risk_policy=protocol.risk_policy,
    )


def run_frozen_multiplier_robustness() -> MultiplierRobustnessReport:
    """Execute development seeds only and evaluate the frozen robustness gate."""
    protocol = frozen_multiplier_robustness_protocol()
    reports: dict[SyntheticProcess, MultiplierMonteCarloReport] = {}
    primary: list[ProcessRobustnessSummary] = []
    for process in _MULTIPLIER_PROCESSES:
        monte_carlo = _run_cell(
            process=process,
            barrier=protocol.primary_barrier,
            protocol=protocol,
        )
        reports[process] = monte_carlo
        primary.append(
            summarize_process_robustness(
                process=process,
                report=monte_carlo,
                confidence=protocol.bootstrap_confidence,
                resamples=protocol.bootstrap_resamples,
                seed=protocol.bootstrap_seed,
            )
        )

    ou_primary = reports[SyntheticProcess.ORNSTEIN_UHLENBECK]
    sensitivity: list[SensitivityRobustnessSummary] = []
    for cell in protocol.sensitivity:
        monte_carlo = (
            ou_primary
            if cell.barrier == protocol.primary_barrier
            else _run_cell(
                process=SyntheticProcess.ORNSTEIN_UHLENBECK,
                barrier=cell.barrier,
                protocol=protocol,
            )
        )
        sensitivity.append(
            SensitivityRobustnessSummary(
                name=cell.name,
                paired_brier=paired_bootstrap_summary(
                    _paired_differences(monte_carlo),
                    confidence=protocol.bootstrap_confidence,
                    resamples=protocol.bootstrap_resamples,
                    seed=protocol.bootstrap_seed,
                ),
                holdouts_opened=monte_carlo.holdouts_opened,
            )
        )

    return evaluate_multiplier_robustness(
        primary=tuple(primary),
        sensitivity=tuple(sensitivity),
    )
